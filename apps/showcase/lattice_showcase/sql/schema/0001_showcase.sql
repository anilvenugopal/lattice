-- The showcase's tables: sample items, their dependencies, jobs and messages. They hold
-- sample data for demonstrating Lattice's components, not a business domain. Lattice's
-- migration runner creates the showcase schema first.

-- A sample record with one column of every kind the grid shows.
-- id is BY DEFAULT so a new item can take its ref from its id in one statement.
CREATE TABLE showcase.item (
  id          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref         varchar(16)   NOT NULL UNIQUE,
  name        varchar(255)  NOT NULL,
  category    varchar(32)   NOT NULL DEFAULT 'general',
  status      varchar(16)   NOT NULL DEFAULT 'new',
  priority    varchar(16)   NOT NULL DEFAULT 'normal',
  owner_id    bigint        REFERENCES lattice.app_user (id) ON DELETE SET NULL,
  parent_id   bigint        REFERENCES showcase.item (id) ON DELETE SET NULL,
  amount      numeric(14,2) NOT NULL DEFAULT 0,
  progress    integer       NOT NULL DEFAULT 0,
  score       numeric(5,1)  NOT NULL DEFAULT 0,
  tags        varchar(255)  NOT NULL DEFAULT '',        -- comma-separated
  starred     boolean       NOT NULL DEFAULT false,
  country     varchar(64)   NOT NULL DEFAULT '',        -- Natural Earth country name
  notes       text          NOT NULL DEFAULT '',
  due_on      date,
  created_at  timestamp     NOT NULL DEFAULT lattice.utc_now(),
  updated_at  timestamp     NOT NULL DEFAULT lattice.utc_now()
);
CREATE INDEX item_status ON showcase.item (status);
CREATE INDEX item_owner_id ON showcase.item (owner_id);
CREATE INDEX item_parent_id ON showcase.item (parent_id);

-- "from_id must be done before to_id": the dependency graph between items.
CREATE TABLE showcase.item_link (
  from_id bigint NOT NULL REFERENCES showcase.item (id) ON DELETE CASCADE,
  to_id   bigint NOT NULL REFERENCES showcase.item (id) ON DELETE CASCADE,
  PRIMARY KEY (from_id, to_id)
);
CREATE INDEX item_link_to ON showcase.item_link (to_id);

-- A background job run. There is no worker; jobs.background() moves rows along in
-- development.
CREATE TABLE showcase.job (
  id           bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name         varchar(255) NOT NULL,
  job_type     varchar(64)  NOT NULL,
  status       varchar(16)  NOT NULL DEFAULT 'queued',
  progress     integer      NOT NULL DEFAULT 0,
  attempts     integer      NOT NULL DEFAULT 1,
  submitted_by bigint       REFERENCES lattice.app_user (id) ON DELETE SET NULL,
  created_at   timestamp    NOT NULL DEFAULT lattice.utc_now(),
  started_at   timestamp,
  finished_at  timestamp,
  error        text         NOT NULL DEFAULT ''
);
CREATE INDEX job_status ON showcase.job (status);

-- A mailbox message owned by one user.
CREATE TABLE showcase.message (
  id             bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  owner_id       bigint       NOT NULL REFERENCES lattice.app_user (id) ON DELETE CASCADE,
  folder         varchar(16)  NOT NULL DEFAULT 'inbox',
  sender_name    varchar(255) NOT NULL,
  sender_email   varchar(255) NOT NULL,
  subject        varchar(255) NOT NULL,
  body           text         NOT NULL DEFAULT '',
  labels         varchar(255) NOT NULL DEFAULT '',
  has_attachment boolean      NOT NULL DEFAULT false,
  is_read        boolean      NOT NULL DEFAULT false,
  is_starred     boolean      NOT NULL DEFAULT false,
  received_at    timestamp    NOT NULL DEFAULT lattice.utc_now()
);
CREATE INDEX message_owner_id ON showcase.message (owner_id);
