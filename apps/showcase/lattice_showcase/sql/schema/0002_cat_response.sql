-- Catastrophe response (docs/plans/step-10-cat-response-showcase.md). The app sits beside
-- the systems of record: locations and claims are copies, with their system-of-record
-- numbers; events, footprints, exposure runs, assignments and estimates are its own.
-- Each location's point lives in geoengine's layer 'locations' (external_id = ref).

-- The exposure snapshot: one insured location per row, as of the nightly extract.
CREATE TABLE showcase.location (
  id            bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ref           varchar(16)   NOT NULL UNIQUE,               -- LOC-000001; geo external_id
  policy_number varchar(20)   NOT NULL,
  insured       varchar(255)  NOT NULL,
  line          varchar(24)   NOT NULL,                      -- homeowners, commercial_property, auto
  occupancy     varchar(32)   NOT NULL,
  construction  varchar(24)   NOT NULL,                      -- frame, masonry, steel, manufactured
  year_built    integer       NOT NULL,
  tiv           numeric(14,0) NOT NULL,                      -- total insured value
  deductible    numeric(12,0) NOT NULL,
  state         varchar(2)    NOT NULL,
  county_fips   varchar(5)    NOT NULL,
  county        varchar(64)   NOT NULL,
  city          varchar(64)   NOT NULL,
  snapshot_on   date          NOT NULL
);
CREATE INDEX location_county ON showcase.location (county_fips);

-- People who respond: surveyors and adjusters (not users of the app).
CREATE TABLE showcase.staff (
  id    bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name  varchar(128) NOT NULL,
  role  varchar(16)  NOT NULL,                                -- surveyor, adjuster, lead
  team  varchar(32)  NOT NULL,
  home  varchar(64)  NOT NULL                                 -- where they are based
);

-- A catastrophe the carrier responds to. `details` holds the peril's own fields
-- (category and wind for a hurricane, hail size, acres burned…), from the event form.
CREATE TABLE showcase.event (
  id          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        varchar(16)   NOT NULL UNIQUE,                  -- CAT-2604
  name        varchar(128)  NOT NULL,
  peril       varchar(16)   NOT NULL,                         -- hurricane, hail, freeze, wildfire
  status      varchar(16)   NOT NULL DEFAULT 'watch',         -- watch, landfall, response, recovery, closed
  pcs_code    varchar(16)   NOT NULL DEFAULT '',              -- the industry catastrophe code, once assigned
  region      varchar(128)  NOT NULL DEFAULT '',
  starts_on   date          NOT NULL,
  landfall_on date,
  closed_on   date,
  details     jsonb         NOT NULL DEFAULT '{}',
  created_at  timestamp     NOT NULL DEFAULT lattice.utc_now(),
  updated_at  timestamp     NOT NULL DEFAULT lattice.utc_now()
);

-- Each version of an event's affected area: a forecast advisory, a fire perimeter update.
-- The shapes are a geoengine layer; the latest version is the event's footprint.
CREATE TABLE showcase.footprint (
  id         bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id   bigint       NOT NULL REFERENCES showcase.event (id) ON DELETE CASCADE,
  version    integer      NOT NULL,
  label      varchar(128) NOT NULL,                           -- "Advisory 12", "Perimeter 3 Aug"
  source     varchar(16)  NOT NULL,                           -- counties, upload, drawn, advisory
  layer      varchar(128) NOT NULL,                           -- geo.layer.key
  created_at timestamp    NOT NULL DEFAULT lattice.utc_now(),
  UNIQUE (event_id, version)
);

-- One exposure run: which locations a footprint version covers, kept as a snapshot.
CREATE TABLE showcase.exposure_run (
  id           bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id     bigint        NOT NULL REFERENCES showcase.event (id) ON DELETE CASCADE,
  footprint_id bigint        NOT NULL REFERENCES showcase.footprint (id) ON DELETE CASCADE,
  status       varchar(16)   NOT NULL DEFAULT 'queued',       -- queued, running, done, failed
  progress     integer       NOT NULL DEFAULT 0,
  locations    integer       NOT NULL DEFAULT 0,
  tiv          numeric(16,0) NOT NULL DEFAULT 0,
  started_at   timestamp,
  finished_at  timestamp,
  created_at   timestamp     NOT NULL DEFAULT lattice.utc_now()
);

CREATE TABLE showcase.exposure (
  run_id      bigint NOT NULL REFERENCES showcase.exposure_run (id) ON DELETE CASCADE,
  location_id bigint NOT NULL REFERENCES showcase.location (id) ON DELETE CASCADE,
  PRIMARY KEY (run_id, location_id)
);

-- A response zone within an event, with its lead.
CREATE TABLE showcase.zone (
  id       bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id bigint       NOT NULL REFERENCES showcase.event (id) ON DELETE CASCADE,
  name     varchar(64)  NOT NULL,
  lead_id  bigint       REFERENCES showcase.staff (id) ON DELETE SET NULL,
  UNIQUE (event_id, name)
);

-- A claim, copied from the claims system (claim_number is its number there).
CREATE TABLE showcase.claim (
  id           bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_number varchar(20)   NOT NULL UNIQUE,
  event_id     bigint        REFERENCES showcase.event (id) ON DELETE SET NULL,
  location_id  bigint        NOT NULL REFERENCES showcase.location (id),
  loss_date    date          NOT NULL,
  reported_at  timestamp     NOT NULL,
  channel      varchar(16)   NOT NULL,                        -- phone, app, agent, web
  cause        varchar(32)   NOT NULL,                        -- wind, flood, hail, fire, freeze…
  severity     varchar(16)   NOT NULL,                        -- minor, moderate, major, total
  status       varchar(16)   NOT NULL DEFAULT 'new',          -- new, assigned, inspected, settled, closed
  priority     boolean       NOT NULL DEFAULT false,
  estimate     numeric(14,0) NOT NULL DEFAULT 0,
  paid         numeric(14,0) NOT NULL DEFAULT 0,
  zone_id      bigint        REFERENCES showcase.zone (id) ON DELETE SET NULL,
  surveyor_id  bigint        REFERENCES showcase.staff (id) ON DELETE SET NULL,
  adjuster_id  bigint        REFERENCES showcase.staff (id) ON DELETE SET NULL,
  closed_at    timestamp,
  updated_at   timestamp     NOT NULL DEFAULT lattice.utc_now()
);
CREATE INDEX claim_event ON showcase.claim (event_id, reported_at);
CREATE INDEX claim_location ON showcase.claim (location_id);

-- A Monte Carlo loss estimate for an event's footprint (illustrative), and its simulations.
CREATE TABLE showcase.loss_run (
  id           bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id     bigint        NOT NULL REFERENCES showcase.event (id) ON DELETE CASCADE,
  footprint_id bigint        NOT NULL REFERENCES showcase.footprint (id) ON DELETE CASCADE,
  simulations  integer       NOT NULL,
  assumptions  jsonb         NOT NULL DEFAULT '{}',
  status       varchar(16)   NOT NULL DEFAULT 'queued',
  progress     integer       NOT NULL DEFAULT 0,
  mean_loss    numeric(16,0),
  p99_loss     numeric(16,0),                                 -- 1 in 100
  p996_loss    numeric(16,0),                                 -- 1 in 250
  started_at   timestamp,
  finished_at  timestamp,
  created_at   timestamp     NOT NULL DEFAULT lattice.utc_now()
);

CREATE TABLE showcase.loss_sample (
  run_id     bigint        NOT NULL REFERENCES showcase.loss_run (id) ON DELETE CASCADE,
  simulation integer       NOT NULL,
  loss       numeric(16,0) NOT NULL,
  PRIMARY KEY (run_id, simulation)
);
