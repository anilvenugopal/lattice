-- The demo app's tables: work items, jobs and messages. Lattice's migration runner
-- creates the demo schema first.

-- A case that moves through review: a submission, request, ticket or claim.
-- id is BY DEFAULT so a new item can take its ref from its id in one statement.
CREATE TABLE demo.work_item (
  id          bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref         varchar(32)      NOT NULL UNIQUE,
  title       varchar(255)     NOT NULL,
  account     varchar(255)     NOT NULL DEFAULT '',
  status      varchar(32)      NOT NULL DEFAULT 'new',
  priority    varchar(16)      NOT NULL DEFAULT 'normal',
  owner_id    bigint           REFERENCES lattice.app_user (id) ON DELETE SET NULL,
  amount      double precision NOT NULL DEFAULT 0,
  description text             NOT NULL DEFAULT '',
  received_at timestamp        NOT NULL DEFAULT lattice.utc_now(),
  updated_at  timestamp        NOT NULL DEFAULT lattice.utc_now()
);
CREATE INDEX work_item_status ON demo.work_item (status);

-- A background job run. The demo has no worker; jobs.background() moves rows along
-- in development.
CREATE TABLE demo.job (
  id           bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name         varchar(255) NOT NULL,
  job_type     varchar(64)  NOT NULL,
  status       varchar(16)  NOT NULL DEFAULT 'queued',
  progress     integer      NOT NULL DEFAULT 0,
  attempts     integer      NOT NULL DEFAULT 1,
  submitted_by bigint       REFERENCES lattice.app_user (id) ON DELETE SET NULL,
  created_at   timestamp    NOT NULL DEFAULT lattice.utc_now(),
  started_at   timestamp,
  finished_at  timestamp,
  error        text         NOT NULL DEFAULT ''
);
CREATE INDEX job_status ON demo.job (status);

-- A mailbox message owned by one user.
CREATE TABLE demo.message (
  id             bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  owner_id       bigint       NOT NULL REFERENCES lattice.app_user (id) ON DELETE CASCADE,
  folder         varchar(16)  NOT NULL DEFAULT 'inbox',
  sender_name    varchar(255) NOT NULL,
  sender_email   varchar(255) NOT NULL,
  subject        varchar(255) NOT NULL,
  body           text         NOT NULL DEFAULT '',
  labels         varchar(255) NOT NULL DEFAULT '',
  has_attachment boolean      NOT NULL DEFAULT false,
  is_read        boolean      NOT NULL DEFAULT false,
  is_starred     boolean      NOT NULL DEFAULT false,
  received_at    timestamp    NOT NULL DEFAULT lattice.utc_now()
);
CREATE INDEX message_owner_id ON demo.message (owner_id);
