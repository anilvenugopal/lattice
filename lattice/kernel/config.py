"""Settings read from LATTICE_* environment variables or `.env`. See `.env.example`."""

from __future__ import annotations

from typing import Literal

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Every setting is an environment variable named LATTICE_ plus the field name in capitals.

    The descriptions here are published in the developer documentation
    (Reference › Settings, generated by `lattice docs build`).
    """

    model_config = SettingsConfigDict(env_file=".env", env_prefix="LATTICE_", extra="ignore")

    app_name: str = Field("Lattice", description="Name shown in the top bar, page titles and the sign-in page.")
    app_env: str = Field("development", description="`development`, `test` or `production`. Production turns off the API docs page, seed data and the showcase job loop, and turns on secure cookies.")
    brand_logo_light: str = Field("/static/brand/logo-light.svg", description="Logo for light mode, shown in the top bar and on the sign-in page.")
    brand_logo_dark: str = Field("/static/brand/logo-dark.svg", description="Logo for dark mode.")
    brand_favicon: str = Field("", description="The browser tab icon. Empty: the light and dark logos, by the browser's colour scheme.")
    brand_show_name: bool = Field(True, description="Show the app name next to the logo. Set false when the logo images already contain the name.")
    secret_key: str = Field("dev-secret-change-me", description="Signs the flash and OIDC cookies. Set a long random value in production.")
    database_url: str = Field("postgresql+psycopg://lattice:lattice@127.0.0.1:5436/lattice",
                              description="The Postgres database, as a SQLAlchemy URL with the psycopg driver.")
    host: str = Field("showcase_host.main:app", description="The host the `lattice` command line runs and seeds, as `module:attribute`.")

    session_idle_minutes: int = Field(480, description="A session ends after this many minutes without a request.")
    session_max_hours: int = Field(24, description="A session ends this many hours after sign-in, whatever the activity.")
    cookie_secure: bool | None = Field(None, description="Secure flag on cookies. Unset: on in production or when the request is HTTPS.")
    chart_colors: Literal["brand", "neutral"] = Field("brand", description="How charts that name no colour mode are coloured: `brand`, shades of the theme colour, or `neutral`, greys (ADR 0015).")
    notification_days: int = Field(90, description="Notifications older than this many days are deleted (ADR 0016).")
    notification_digest_hour: int = Field(7, description="Hour of the day (UTC) after which the daily notification summary is emailed.")
    public_url: str = Field("http://localhost:8000", description="The site's address as people reach it, for links in emails.")
    mail_from: str = Field("Lattice <noreply@localhost>", description="Sender of the emails Lattice sends.")
    files_dir: str = Field("var/files", description="Folder where attachment files are kept (ADR 0017). Back it up with the database.")
    attachment_max_mb: int = Field(25, description="Largest attachment, in megabytes.")
    attachment_types: str = Field("pdf,png,jpg,jpeg,gif,webp,heic,txt,csv,doc,docx,xls,xlsx,ppt,pptx,odt,ods,eml,msg,zip",
                                  description="File types attachments may have, as extensions separated by commas.")
    folder_stores: dict[str, str] = Field(default_factory=dict, description='Mounted shares people may browse with the folder picker, as JSON: {"Claims share": "/mnt/claims"}.')
    smtp_host: str = Field("", description="Mail server. Empty: emails are not sent but kept as logged, readable in Administration › Email.")
    smtp_port: int = Field(587, description="Mail server port.")
    smtp_username: str = Field("", description="Mail server user, if it needs one.")
    smtp_password: str = Field("", description="Mail server password.")
    smtp_starttls: bool = Field(True, description="Use STARTTLS on the mail server connection.")
    grid_query_timeout_seconds: float = Field(15, description="A grid query (rows, count, export, Ctrl+J results) running longer than this is cancelled, and the user is asked to narrow the search or filters.")
    bcrypt_rounds: int = Field(12, description="bcrypt cost for password hashes.")

    password_login_enabled: bool = Field(True, description="Show the email and password form on the sign-in page.")

    oidc_issuer: str = Field("", description="OIDC issuer URL. Set with `oidc_client_id` to show single sign-on.")
    oidc_client_id: str = Field("", description="OIDC client (application) id.")
    oidc_client_secret: str = Field("", description="OIDC client secret, for confidential clients.")
    oidc_redirect_uri: str = Field("http://localhost:8000/auth/oidc/callback", description="Callback URL registered with the identity provider.")
    oidc_scopes: str = Field("openid email profile", description="Scopes requested at sign-in.")
    oidc_provider_label: str = Field("Single sign-on", description="Text on the sign-in button: Continue with …")
    oidc_default_role: str = Field("", description="Role given to a new user on first SSO sign-in. Empty: no role, and an administrator must grant one.")
    oidc_trust_email: bool = Field(False, description="Link an SSO sign-in to an existing account by email even without `email_verified` in the token. Only for an identity provider whose emails your organisation controls.")

    @property
    def is_production(self) -> bool:
        return self.app_env == "production"

    @property
    def oidc_enabled(self) -> bool:
        return bool(self.oidc_issuer and self.oidc_client_id)


settings = Settings()
